const COUNTRY_CODES = new Set(CHECKOUT_COUNTRIES.map((country) => country.code));

export function normalizeCheckoutCountry(value: unknown) {
  if (typeof value !== "string") {
    return "RO";
  }

  const code = value.trim().toUpperCase();

  return COUNTRY_CODES.has(code) ? code : "RO";
}

export function isRomaniaCountry(value: unknown) {
  return normalizeCheckoutCountry(value) === "RO";
}
